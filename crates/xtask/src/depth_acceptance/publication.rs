use super::{effect, input::View, Effect};
use crate::support_matrix::{self, SupportMatrixArtifact};
use std::{collections::BTreeSet, path::Path};

type Qualification = (String, String, String, String);
pub(super) fn qualifications(view: &View) -> Result<BTreeSet<Qualification>, String> {
    let path = support_matrix::JSON_OUTPUT_PATH;
    let artifact: SupportMatrixArtifact =
        serde_json::from_value(view.json(path)?).map_err(|e| e.to_string())?;
    if let Some(error) = artifact.revision_error() {
        return Err(error);
    }
    let markdown = view.source.read(support_matrix::MARKDOWN_OUTPUT_PATH)?;
    let start = "<!-- support-matrix-published:start -->";
    let end = "<!-- support-matrix-published:end -->";
    if markdown.matches(start).count() != 1 || markdown.matches(end).count() != 1 {
        return Err("invalid support Markdown generated block".into());
    }
    let body = markdown
        .split_once(start)
        .ok_or("missing support Markdown start")?
        .1
        .split_once(end)
        .ok_or("missing support Markdown end")?
        .0;
    if body.trim() != support_matrix::render_markdown_projection(&artifact.rows).trim() {
        return Err("support Markdown disagrees with its revision's JSON".into());
    }
    let mut rows = BTreeSet::new();
    let mut values = BTreeSet::new();
    for row in artifact.rows {
        if !rows.insert((row.agent.clone(), row.version.clone(), row.target.clone())) {
            return Err("duplicate support row".into());
        }
        if let Some(depth) = row.depth {
            let mut ids = BTreeSet::new();
            for promise in depth.promises {
                if !ids.insert(promise.operation.clone()) {
                    return Err("duplicate promise operation".into());
                }
                if promise.qualified {
                    values.insert((
                        row.agent.clone(),
                        row.version.clone(),
                        row.target.clone(),
                        format!("promise {}", promise.operation),
                    ));
                }
            }
            let mut ids = BTreeSet::new();
            for cap in depth.capabilities {
                if !ids.insert(cap.id.clone()) {
                    return Err("duplicate capability qualification".into());
                }
                if cap.depth_qualified {
                    values.insert((
                        row.agent.clone(),
                        row.version.clone(),
                        row.target.clone(),
                        format!("capability {}", cap.id),
                    ));
                }
            }
        }
    }
    Ok(values)
}
fn cells(view: &View) -> Result<BTreeSet<(String, String)>, String> {
    let raw = view
        .source
        .read(crate::capability_matrix::DEFAULT_OUT_PATH)?;
    let prefix = "# Capability matrix — Unified Agent API\n\nStatus: Approved  \nApproved (UTC): 2026-02-21\n\nThis file is generated by `cargo run -p xtask -- capability-matrix`.\nCanonical publication target profile: ";
    let rest = raw
        .strip_prefix(prefix)
        .ok_or("unsupported capability matrix preamble")?;
    let (_, body) = rest.split_once("\nThis inventory documents backend capability advertising, not support or promotion status.\nDo not edit by hand.\n\n").ok_or("unsupported capability matrix preamble")?;
    let mut columns: Option<Vec<String>> = None;
    let mut result = BTreeSet::new();
    let mut seen = BTreeSet::new();
    let mut expect_separator = false;
    for line in body.lines() {
        if line.is_empty() || (line.starts_with("## `") && line.ends_with('`')) {
            continue;
        }
        if !line.starts_with('|') || !line.ends_with('|') {
            return Err("unsupported capability table format".into());
        }
        let parts: Vec<_> = line.trim_matches('|').split('|').map(str::trim).collect();
        if parts.first() == Some(&"capability id") {
            let ids = parts[1..]
                .iter()
                .map(|v| {
                    v.strip_prefix('`')
                        .and_then(|v| v.strip_suffix('`'))
                        .filter(|s| !s.is_empty())
                        .map(str::to_owned)
                        .ok_or("invalid capability header")
                })
                .collect::<Result<Vec<_>, _>>()?;
            if ids.iter().collect::<BTreeSet<_>>().len() != ids.len() {
                return Err("duplicate capability backend column".into());
            }
            if columns.as_ref().is_some_and(|c| c != &ids) {
                return Err("inconsistent capability headers".into());
            }
            columns = Some(ids);
            expect_separator = true;
            continue;
        }
        if expect_separator {
            if parts.len() != columns.as_ref().ok_or("missing capability header")?.len() + 1
                || !parts.iter().all(|p| *p == "---")
            {
                return Err("invalid capability table separator".into());
            }
            expect_separator = false;
            continue;
        }
        let ids = columns.as_ref().ok_or("capability row before header")?;
        if parts.len() != ids.len() + 1 {
            return Err("invalid capability row width".into());
        }
        let cap = parts[0]
            .strip_prefix('`')
            .and_then(|v| v.strip_suffix('`'))
            .filter(|s| !s.is_empty())
            .ok_or("invalid capability id cell")?;
        if !seen.insert(cap.to_owned()) {
            return Err("duplicate capability row".into());
        }
        for (agent, value) in ids.iter().zip(&parts[1..]) {
            match *value {
                "✅" => {
                    result.insert((agent.clone(), cap.into()));
                }
                "—" => {}
                _ => return Err("unsupported capability cell".into()),
            }
        }
    }
    if expect_separator
        || (columns.is_some() && seen.is_empty())
        || (columns.is_none() && !body.trim().is_empty())
    {
        return Err("incomplete capability table".into());
    }
    Ok(result)
}
pub(super) fn detect(
    before: &View,
    after: &View,
    effects: &mut BTreeSet<Effect>,
) -> Result<(), String> {
    let previous = qualifications(before)?;
    for (agent, version, target, kind) in qualifications(after)?.difference(&previous) {
        if agent == &after.entry.agent_id {
            effect(
                effects,
                version,
                Some(target),
                support_matrix::JSON_OUTPUT_PATH,
                kind,
            );
        }
    }
    let previous = cells(before)?;
    let current = cells(after)?;
    for (agent, cap) in current.difference(&previous) {
        if agent != &after.entry.agent_id {
            continue;
        }
        for (version, record) in &after.records {
            if record
                .policy
                .selection
                .enrollment
                .capabilities
                .iter()
                .any(|c| &c.id == cap)
            {
                effect(
                    effects,
                    version,
                    None,
                    crate::capability_matrix::DEFAULT_OUT_PATH,
                    &format!("published capability {cap}"),
                );
            }
        }
    }
    super::runtime::support(before, after, effects)?;
    super::runtime::advertising(before, after, effects)?;
    Ok(())
}

pub(super) fn validate_current(workspace: &Path, after: &View) -> Result<(), String> {
    let expected = crate::capability_matrix::generate_markdown_for_workspace(workspace)?;
    if after
        .source
        .read(crate::capability_matrix::DEFAULT_OUT_PATH)?
        != expected
    {
        return Err("capability publication is stale".into());
    }
    crate::capability_publication::audit_current_capability_publication(workspace)?;
    // The ordinary validator independently checks actual current rows against derived depth facts.
    let artifact: SupportMatrixArtifact =
        serde_json::from_value(after.json(support_matrix::JSON_OUTPUT_PATH)?)
            .map_err(|e| e.to_string())?;
    support_matrix::validate_publication_consistency(workspace, &artifact.rows)
        .map_err(|issues| support_matrix::format_publication_issues(&issues))?;
    Ok(())
}
